# Copies the OnlineCoop add-on into the game's mods folder. Game files are
# never touched: the add-on lives in its own folder and overrides scripts by
# name only while it is enabled in the game's Mods menu. A previous copy of
# the add-on is moved to bunker/backups first. The one game script the add-on
# overrides is not redistributed: it is rebuilt here from this installation
# (see mod/OnlineCoop/patches/ModEventHandler.coop.txt).
#
#   ./InstallMod.ps1                       install / update
#   ./InstallMod.ps1 -Uninstall            remove (after a backup)
param(
    [string]$GameDir = 'F:\SteamLibrary\steamapps\common\Amnesia The Bunker',
    [switch]$Uninstall
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$source = Join-Path $root 'mod/OnlineCoop'
$mods = Join-Path $GameDir 'mods'
$target = Join-Path $mods 'OnlineCoop'
if(-not (Test-Path (Join-Path $GameDir 'AmnesiaTheBunker.exe'))) { throw "Amnesia: The Bunker not found in '$GameDir'" }

# Writes the add-on's copy of the game's ModEventHandler: the player's own
# script plus the [COOP] lines listed in patches/ModEventHandler.coop.txt.
function Write-CoopEventHandler([string]$GameDir, [string]$Target) {
    $spec = Join-Path $Target 'patches/ModEventHandler.coop.txt'
    $ops = @(); $gameScript = $null; $tested = $null
    foreach($line in Get-Content -LiteralPath $spec) {
        if($line -match '^\s*(#|$)') { continue }
        $parts = $line.Split('|')
        switch($parts[0]) {
            'source' { $gameScript = $parts[1] }
            'sha256' { $tested = $parts[1] }
            default  { $ops += ,@($parts[0], $parts[1], $parts[2].Replace('\t', "`t")) }
        }
    }
    $stock = Join-Path $GameDir $gameScript
    if(-not (Test-Path -LiteralPath $stock)) { throw "Game script not found: $stock" }
    if((Get-FileHash -LiteralPath $stock -Algorithm SHA256).Hash -ne $tested) {
        Write-Warning "$gameScript differs from the tested game version: patching by anchors."
    }
    $text = [IO.File]::ReadAllText($stock)
    $nl = if($text.Contains("`r`n")) { "`r`n" } else { "`n" }
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.AddRange([string[]]($text -split [regex]::Escape($nl)))
    foreach($op in $ops) {
        $kind, $anchor, $insert = $op
        $hits = @(for($i = 0; $i -lt $lines.Count; $i++) { if($lines[$i].Trim() -eq $anchor) { $i } })
        if($hits.Count -ne 1) { throw "Anchor '$anchor' found $($hits.Count) times in $($gameScript): update the add-on." }
        $at = $hits[0]
        switch($kind) {
            'after'  { $lines.Insert($at + 1, $insert) }
            'before' { $lines.Insert($at, $insert) }
            'body'   {
                $open = $at + 1
                while($open -lt $lines.Count -and $lines[$open].Trim() -ne '{') { $open++ }
                if($open -ge $lines.Count) { throw "No block after '$anchor' in $gameScript" }
                $lines.Insert($open + 1, $insert)
            }
            default  { throw "Unknown instruction '$kind' in $spec" }
        }
    }
    $header = @(
        "// Generated by the OnlineCoop installer from this installation's $gameScript.",
        "// Lines marked [COOP] are the add-on's additions (GPL-3.0-or-later, see",
        "// patches/ModEventHandler.coop.txt); everything else is the game's own",
        "// script, which the add-on does not redistribute.",
        '')
    $out = Join-Path $Target $gameScript
    New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
    [IO.File]::WriteAllText($out, (($header + $lines) -join $nl), (New-Object Text.UTF8Encoding($false)))
}

if(Test-Path $target) {
    $backup = Join-Path $root ('backups/OnlineCoop_' + (Get-Date -Format 'yyyyMMdd_HHmmss'))
    New-Item -ItemType Directory -Force (Split-Path $backup) | Out-Null
    Move-Item -LiteralPath $target -Destination $backup
    Write-Output "Previous add-on moved to $backup"
}
if($Uninstall) { Write-Output 'OnlineCoop add-on removed.'; return }

Copy-Item -LiteralPath $source -Destination $target -Recurse
Write-CoopEventHandler -GameDir $GameDir -Target $target
# The avatar's animations are private copies of the player's own, taken
# from this installation (see tools/MakePartnerEntity.py): shared files
# would break the real player's animations.
foreach($line in Get-Content -LiteralPath (Join-Path $target 'entities/coop/anims.txt')) {
    if($line -match '^\s*(#|$)') { continue }
    $from, $to = $line -split '\|'
    $dest = Join-Path $target $to
    New-Item -ItemType Directory -Force (Split-Path $dest) | Out-Null
    Copy-Item -LiteralPath (Join-Path $GameDir $from) -Destination $dest
}
Write-Output "OnlineCoop add-on installed in $target"
Write-Output 'Enable it from the game: main menu > Mods > select "Online Co-op (experimental)" > Launch.'
